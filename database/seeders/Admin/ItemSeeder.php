    /**
     * One piece's price per item, keyed by file_prefix, for StoreVariantSeeder.
     *
     * @return array<string, array{piece: float, sizes?: array<string, float>}>
     */
    public function piecePrices(): array
    {
        return array_column(
            array_map(fn (array $item): array => ['key' => $item['file_prefix'], 'price' => $item['price']], $this->items),
            'price',
            'key',
        );
    }

    /** @var array<string, array<string, int>> lookup table => name => id */
    private array $ids = [];

    public function run(): void
    {
        /** @var ItemVariantGenerationService $generator */
        $generator = app(ItemVariantGenerationService::class);

        $this->ids = [
            'category' => ItemCategory::pluck('id', 'category_name')->all(),
            'color' => ItemColor::pluck('id', 'name')->all(),
            'size' => ItemSize::pluck('id', 'name')->all(),
            'packaging' => ItemPackagingType::pluck('id', 'name')->all(),
        ];

        // Safe on a live database: items already there (matched by file_prefix) are left alone.
        $existing = Item::withoutGlobalScopes()->pluck('file_prefix')->flip()->all();

        foreach ($this->items as $data) {
            if (isset($existing[$data['file_prefix']])) {
                continue;
            }

            $packaging = $this->resolvePackaging($data);

            $item = Item::factory()
                ->withPicsumId($data['picsum_id'])
                ->create([
                    'product_name' => $data['product_name'],
                    'file_prefix' => $data['file_prefix'],
                    'product_description' => $data['product_description'],
                    'packaging_details' => $this->describePackaging($data['packaging']),
                    'item_category_id' => $this->idFor('category', $data['category'], $data),
                    'status' => 'draft',
                    'is_incomplete' => true,
                ]);

            $item->colors()->sync(array_map(fn (string $name) => $this->idFor('color', $name, $data), $data['colors']));
            $item->sizes()->sync(array_map(fn (string $name) => $this->idFor('size', $name, $data), $data['sizes']));
            $item->packagingTypes()->sync(array_map(
                fn (array $row) => ['quantity' => $row['quantity']],
                $packaging,
            ));

            $images = $this->seedDeterministicVariantImages($item, $data);

            $item->update([
                'general_images' => $images
            ]);

            $generator->sync($item);

            $this->populatePackagingQuantitiesAndCbm($item, $packaging);
            $this->evaluateDraftStatus($item, $data['status']);
        }
    }

    private function idFor(string $table, string $name, array $data): int
    {
        return $this->ids[$table][$name]
            ?? throw new RuntimeException("ItemSeeder: unknown {$table} \"{$name}\" on \"{$data['product_name']}\".");
    }

    /**
     * @return array<int, array{quantity: int, cbm: float}> keyed by packaging type id
     */
    private function resolvePackaging(array $data): array
    {
        $rows = [];
        foreach ($data['packaging'] as $row) {
            $rows[$this->idFor('packaging', $row['type'], $data)] = [
                'quantity' => max(1, (int) $row['quantity']),
                'cbm' => (float) ($row['cbm'] ?? 0),
            ];
        }

        return $rows;
    }

    /** "Sold by the piece, or in boxes of 12 and cartons of 144." */
    private function describePackaging(array $packaging): string
    {
        $plural = ['Box' => 'boxes', 'Doz' => 'dozens'];
        $byPiece = false;
        $packs = [];

        foreach ($packaging as $row) {
            if ($row['type'] === 'Piece') {
                $byPiece = true;
                continue;
            }
            $packs[] = ($plural[$row['type']] ?? strtolower($row['type']).'s').' of '.number_format((int) $row['quantity']);
        }

        $last = array_pop($packs);
        $packText = $last === null ? '' : 'in '.($packs === [] ? $last : implode(', ', $packs).' and '.$last);

        return 'Sold '.match (true) {
            $byPiece && $packText !== '' => "by the piece, or {$packText}",
            $byPiece => 'by the piece',
            default => $packText,
        }.'.';
    }

    /**
     * Upload whatever real photography is committed for this item and return
     * the keys that genuinely landed.
     *
     * Three things were wrong with the previous version, and together they
     * filled the catalogue with 8,115 broken images:
     *
     *  1. It uploaded to the `s3` disk (MinIO, bucket duka-images) while
     *     App\Services\ImageResolver reads from `r2` (bucket canvas-assets),
     *     so nothing it wrote was ever readable by the application.
     *  2. It looped v1..v9 x 1..5 inventing filenames like
     *     "{prefix}_v3_2.jpg". No such file has ever existed in
     *     storage/app/seed-images — File::exists() failed on every one and the
     *     method returned early, silently.
     *  3. An earlier revision recorded the key regardless of whether the
     *     upload succeeded, which is where the dead keys came from.
     *
     * A key is now recorded only after the object is confirmed present. An
     * item with no committed photography gets an empty array, and the UI draws
     * a PackagingPlaceholder for it — see
     * resources/js/Components/Shared/PackagingPlaceholder.tsx.
     *
     * @return array<int, string> Object keys, possibly empty.
     */
    private function seedDeterministicVariantImages(Item $item, array $data): array
    {
        $prefix = $data['file_prefix'];
        $keys = [];

        // Only the {prefix}_1.jpg .. {prefix}_5.jpg convention is real; those
        // are the files actually committed under storage/app/seed-images.
        for ($i = 1; $i <= 5; $i++) {
            $key = $this->uploadSeedImage($item->id, "{$prefix}_{$i}.jpg");

            if ($key !== null) {
                $keys[] = $key;
            }
        }

        return $keys;
    }

    /**
     * Copy one committed seed image to the image disk.
     *
     * @return string|null The stored key, or null when there is no such file
     *                     or the object store is unreachable. Never a key for
     *                     an object that is not there.
     */
    private function uploadSeedImage(int $itemId, string $fileName): ?string
    {
        $sourcePath = storage_path("app/seed-images/{$fileName}");

        if (! File::exists($sourcePath)) {
            return null;
        }

        $key = "uploads/items/{$itemId}/{$fileName}";

        try {
            $disk = Storage::disk('r2');

            if (! $disk->exists($key)) {
                $disk->put($key, File::get($sourcePath), 'public');
            }

            return $key;
        } catch (\Throwable $e) {
            // Seeding must work offline and without object-store credentials.
            // The item simply ends up with no photography, which is a state
            // the application renders correctly.
            $this->command?->warn("Could not upload {$fileName}: {$e->getMessage()}");

            return null;
        }
    }

    /**
     * @param  array<int, array{quantity: int, cbm: float}>  $packaging  keyed by packaging type id
     */
    private function populatePackagingQuantitiesAndCbm(Item $item, array $packaging): void
    {
        $item->load('variants');

        foreach ($item->variants as $variant) {
            if (method_exists($variant, 'packagingQuantities')) {
                $variant->packagingQuantities()->sync($packaging);
            }
        }
    }

    private function evaluateDraftStatus(Item $item, string $requestedStatus): void
    {
        $item->update([
            'status' => $requestedStatus,
            'is_incomplete' => false,
        ]);

        $item->refresh()->load('variants');
        foreach ($item->variants as $variant) {
            $variant->update(['status' => $requestedStatus]);
        }
    }
